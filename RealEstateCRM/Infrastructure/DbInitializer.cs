using Microsoft.EntityFrameworkCore;
using RealEstateCRM.Data;
using RealEstateCRM.Models;
using RealEstateCRM.Security;

namespace RealEstateCRM.Infrastructure
{
    public static class DbInitializer
    {
        public static async Task InitializeAsync(IServiceProvider services, IConfiguration config, IHostEnvironment env)
        {
            using var scope = services.CreateScope();
            var db = scope.ServiceProvider.GetRequiredService<CrmDbContext>();
            var logger = scope.ServiceProvider.GetRequiredService<ILoggerFactory>().CreateLogger("DbInitializer");

            if (db.Database.GetMigrations().Any())
            {
                await db.Database.MigrateAsync();
            }
            else
            {
                logger.LogWarning("No EF migrations found; creating the schema with EnsureCreated. " +
                                  "Generate migrations (see README) before storing real data.");
                await db.Database.EnsureCreatedAsync();
                await PatchExistingSchemaAsync(db, logger);
            }

            await BootstrapAsync(db, config, env, logger);
        }

        /// <summary>
        /// EnsureCreated does not touch tables that already exist, so databases created before the Stages feature
        /// need the new table and columns added by hand. Safe to run on every start. Remove once EF migrations are used.
        /// </summary>
        private static async Task PatchExistingSchemaAsync(CrmDbContext db, ILogger logger)
        {
            try
            {
                if (db.Database.IsNpgsql())
                {
                    await db.Database.ExecuteSqlRawAsync(@"CREATE TABLE IF NOT EXISTS ""StageTemplates"" (
                        ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        ""CompanyId"" integer NOT NULL,
                        ""Sequence"" integer NOT NULL,
                        ""Name"" character varying(200) NOT NULL,
                        ""Owner"" character varying(100) NULL,
                        ""DefaultDays"" integer NOT NULL,
                        ""Category"" integer NOT NULL)");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE INDEX IF NOT EXISTS ""IX_StageTemplates_CompanyId"" ON ""StageTemplates"" (""CompanyId"")");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE TABLE IF NOT EXISTS ""ProjectDocuments"" (
                        ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        ""CompanyId"" integer NOT NULL,
                        ""ProjectId"" integer NOT NULL REFERENCES ""Projects"" (""Id"") ON DELETE CASCADE,
                        ""MilestoneId"" integer NULL,
                        ""FileName"" character varying(255) NOT NULL,
                        ""ContentType"" character varying(100) NOT NULL,
                        ""SizeBytes"" bigint NOT NULL,
                        ""Data"" bytea NOT NULL,
                        ""Note"" character varying(500) NULL,
                        ""UploadedBy"" character varying(100) NULL,
                        ""UploadedAt"" timestamp with time zone NOT NULL)");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE INDEX IF NOT EXISTS ""IX_ProjectDocuments_ProjectId"" ON ""ProjectDocuments"" (""ProjectId"")");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE INDEX IF NOT EXISTS ""IX_ProjectDocuments_CompanyId"" ON ""ProjectDocuments"" (""CompanyId"")");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE TABLE IF NOT EXISTS ""People"" (
                        ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        ""CompanyId"" integer NOT NULL,
                        ""Name"" character varying(100) NOT NULL)");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE INDEX IF NOT EXISTS ""IX_People_CompanyId"" ON ""People"" (""CompanyId"")");
                    await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Projects"" ADD COLUMN IF NOT EXISTS ""ProjectManager"" character varying(100) NULL");
                    await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""Projects"" ADD COLUMN IF NOT EXISTS ""EscalationOwner"" character varying(100) NULL");
                    await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ProjectMilestones"" ADD COLUMN IF NOT EXISTS ""Owner"" character varying(100) NULL");
                    await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ProjectMilestones"" ADD COLUMN IF NOT EXISTS ""Sequence"" integer NOT NULL DEFAULT 0");
                }
                else if (db.Database.IsSqlite())
                {
                    await db.Database.ExecuteSqlRawAsync(@"CREATE TABLE IF NOT EXISTS ""StageTemplates"" (
                        ""Id"" INTEGER NOT NULL CONSTRAINT ""PK_StageTemplates"" PRIMARY KEY AUTOINCREMENT,
                        ""CompanyId"" INTEGER NOT NULL,
                        ""Sequence"" INTEGER NOT NULL,
                        ""Name"" TEXT NOT NULL,
                        ""Owner"" TEXT NULL,
                        ""DefaultDays"" INTEGER NOT NULL,
                        ""Category"" INTEGER NOT NULL)");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE TABLE IF NOT EXISTS ""People"" (
                        ""Id"" INTEGER NOT NULL CONSTRAINT ""PK_People"" PRIMARY KEY AUTOINCREMENT,
                        ""CompanyId"" INTEGER NOT NULL,
                        ""Name"" TEXT NOT NULL)");
                    await db.Database.ExecuteSqlRawAsync(@"CREATE TABLE IF NOT EXISTS ""ProjectDocuments"" (
                        ""Id"" INTEGER NOT NULL CONSTRAINT ""PK_ProjectDocuments"" PRIMARY KEY AUTOINCREMENT,
                        ""CompanyId"" INTEGER NOT NULL,
                        ""ProjectId"" INTEGER NOT NULL REFERENCES ""Projects"" (""Id"") ON DELETE CASCADE,
                        ""MilestoneId"" INTEGER NULL,
                        ""FileName"" TEXT NOT NULL,
                        ""ContentType"" TEXT NOT NULL,
                        ""SizeBytes"" INTEGER NOT NULL,
                        ""Data"" BLOB NOT NULL,
                        ""Note"" TEXT NULL,
                        ""UploadedBy"" TEXT NULL,
                        ""UploadedAt"" TEXT NOT NULL)");
                    foreach (var col in new[] { "ProjectManager", "EscalationOwner" })
                    {
                        if (!await SqliteHasColumnAsync(db, "Projects", col))
                            await db.Database.ExecuteSqlRawAsync($@"ALTER TABLE ""Projects"" ADD COLUMN ""{col}"" TEXT NULL");
                    }
                    var cols = new List<string>();
                    var conn = db.Database.GetDbConnection();
                    if (conn.State != System.Data.ConnectionState.Open) await conn.OpenAsync();
                    using (var cmd = conn.CreateCommand())
                    {
                        cmd.CommandText = "SELECT name FROM pragma_table_info('ProjectMilestones')";
                        using var r = await cmd.ExecuteReaderAsync();
                        while (await r.ReadAsync()) cols.Add(r.GetString(0));
                    }
                    if (cols.Count > 0 && !cols.Contains("Owner"))
                        await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ProjectMilestones"" ADD COLUMN ""Owner"" TEXT NULL");
                    if (cols.Count > 0 && !cols.Contains("Sequence"))
                        await db.Database.ExecuteSqlRawAsync(@"ALTER TABLE ""ProjectMilestones"" ADD COLUMN ""Sequence"" INTEGER NOT NULL DEFAULT 0");
                }
            }
            catch (Exception ex)
            {
                logger.LogError(ex, "Schema patch failed; the Stages feature may not work until the database is updated.");
            }
        }

        private static async Task<bool> SqliteHasColumnAsync(CrmDbContext db, string table, string column)
        {
            var conn = db.Database.GetDbConnection();
            if (conn.State != System.Data.ConnectionState.Open) await conn.OpenAsync();
            using var cmd = conn.CreateCommand();
            cmd.CommandText = $"SELECT COUNT(*) FROM pragma_table_info('{table}') WHERE name = '{column}'";
            return Convert.ToInt32(await cmd.ExecuteScalarAsync()) > 0;
        }

        /// <summary>
        /// Creates the first company and Owner from configuration (Bootstrap:*). Nothing is created in
        /// production unless these values are provided; Development falls back to a documented test login.
        /// </summary>
        private static async Task BootstrapAsync(CrmDbContext db, IConfiguration config, IHostEnvironment env, ILogger logger)
        {
            var code = config["Bootstrap:CompanyCode"];
            var companyName = config["Bootstrap:CompanyName"];
            var username = config["Bootstrap:AdminUsername"];
            var password = config["Bootstrap:AdminPassword"];

            if (string.IsNullOrWhiteSpace(code) && string.IsNullOrWhiteSpace(username) && string.IsNullOrWhiteSpace(password))
            {
                if (!env.IsDevelopment()) return;

                code = "Test";
                companyName = "Test Company";
                username = "Test";
                password = "Test@12345";
                logger.LogWarning("Development mode: seeding test login Test / Test / Test@12345.");
            }

            if (string.IsNullOrWhiteSpace(code) || string.IsNullOrWhiteSpace(username) || string.IsNullOrWhiteSpace(password))
            {
                logger.LogError("Bootstrap requires CompanyCode, AdminUsername and AdminPassword together; skipping.");
                return;
            }

            if (password.Length < 10 && !env.IsDevelopment())
            {
                logger.LogError("Bootstrap:AdminPassword must be at least 10 characters; skipping.");
                return;
            }

            var company = await db.Companies.FirstOrDefaultAsync(c => c.Code.ToLower() == code.ToLower());
            if (company == null)
            {
                company = new Company { Code = code, Name = string.IsNullOrWhiteSpace(companyName) ? code : companyName };
                db.Companies.Add(company);
                await db.SaveChangesAsync();
            }

            var exists = await db.Users.AnyAsync(u => u.CompanyId == company.Id && u.Username.ToLower() == username.ToLower());
            if (!exists)
            {
                db.Users.Add(new User
                {
                    CompanyId = company.Id,
                    Username = username,
                    PasswordHash = PasswordHasher.Hash(password),
                    Role = Roles.Owner,
                    IsActive = true
                });
                await db.SaveChangesAsync();
                logger.LogInformation("Bootstrapped owner '{Username}' for company '{Code}'.", username, code);
            }
        }
    }
}
